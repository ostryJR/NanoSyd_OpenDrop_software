#!/usr/bin/env node
'use strict';
/*
 * Converts the electrode layout files of GaudiLabs' OpenDropController4_25
 * (https://github.com/GaudiLabs/OpenDrop, GPL-3.0) into js/layouts-data.js.
 *
 * The original files are not strict JSON (they have trailing commas, which Processing's
 * parser accepts), and a page opened from disk can't fetch() files anyway, so the layouts
 * are parsed once here and stored as a plain script.
 *
 * Usage: node tools/convert-layouts.js <path/to/OpenDropController4_25> [out-file]
 */
const fs = require('fs');
const path = require('path');

const [srcDir, outFile = path.join(__dirname, '..', 'js', 'layouts-data.js')] = process.argv.slice(2);
if (!srcDir) {
  console.error('usage: node tools/convert-layouts.js <OpenDropController4_25 folder> [out-file]');
  process.exit(2);
}

const FIRST = ['electrodes', 'electrodes_magnet']; // the two layouts the original switches between
const rank = (name) => (FIRST.includes(name) ? FIRST.indexOf(name) : FIRST.length);
const names = fs
  .readdirSync(srcDir)
  .filter((f) => /^electrodes.*\.json$/.test(f))
  .map((f) => f.slice(0, -'.json'.length))
  .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));

const parseLenient = (text) => JSON.parse(text.replace(/,\s*([}\]])/g, '$1'));

const layouts = {};
for (const name of names) {
  const raw = parseLenient(fs.readFileSync(path.join(srcDir, name + '.json'), 'utf8'));
  if (!Array.isArray(raw)) throw new Error(`${name}: expected an array`);
  layouts[name] = raw.map((r, i) => {
    for (const k of ['x', 'y', 'h', 'v', 'e']) {
      if (typeof r[k] !== 'number' || !Number.isFinite(r[k])) throw new Error(`${name}[${i}].${k} is not a number`);
    }
    if (!Number.isInteger(r.e) || r.e < 0 || r.e >= 144) throw new Error(`${name}[${i}].e is out of range: ${r.e}`);
    return { x: r.x, y: r.y, h: r.h, v: r.v, e: r.e };
  });
}

const body = names
  .map((n) => `    ${JSON.stringify(n)}: [\n${layouts[n].map((r) => '      ' + JSON.stringify(r)).join(',\n')}\n    ]`)
  .join(',\n');

fs.writeFileSync(
  outFile,
  `/* Generated by tools/convert-layouts.js from GaudiLabs/OpenDrop
 * OpenDropController4_25/electrodes*.json (GPL-3.0). Do not edit by hand.
 * One rectangle per entry, in grid units (1 unit = 23 px on OpenDropFrame.png, half a standard
 * electrode): x/y = top-left corner, h/v = width/height, e = electrode ID (column * 8 + row).
 * An electrode drawn as several rectangles (the reservoirs) appears several times. */
(function (root) {
  'use strict';
  var data = {
${body}
  };
  if (typeof module === 'object' && module.exports) module.exports = data;
  else (root.OD = root.OD || {}).layoutData = data;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`
);
console.log(`wrote ${outFile}: ${names.map((n) => `${n} (${layouts[n].length})`).join(', ')}`);
